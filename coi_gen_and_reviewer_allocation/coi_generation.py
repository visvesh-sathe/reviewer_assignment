"""
COI Generation Script (Colab/Interactive Workflow)
Extracts affiliations from paper_info and generates the COI matrix based on reviewer expertise.
Outputs an editable matrix and a backup matrix.
"""

import sys
import os
from pathlib import Path

# Setup paths to ensure we can import the src modules
current_dir = Path(__file__).resolve().parent
repo_root = current_dir.parent
if str(repo_root) not in sys.path:
    sys.path.insert(0, str(repo_root))
if str(repo_root / "src") not in sys.path:
    sys.path.insert(0, str(repo_root / "src"))

from reviewer_assignment.scrubber import AffiliationScrubber
from generate_coi_matrix import generate_coi

def main():
    print("=====================================================")
    print("        Step 1: COI Matrix Generation Flow           ")
    print("=====================================================\n")
    
    # Input Files
    paper_info_path = "input_files/cfg_paper_info.csv"
    reviewer_exp_path = "input_files/cfg_reviewer_expertise.csv"
    
    # Intermediate / Output Files
    scrubbed_affiliations_path = "intermediate_files/paper_id_and_affiliations.csv"
    editable_coi_path = "input_files/cfg_coi.csv"
    backup_coi_path = "output_files/autogenerated_coi.csv"
    report_path = "output_files/coi_report.txt"
    
    if not os.path.exists(paper_info_path) or not os.path.exists(reviewer_exp_path):
        print("Error: Missing required input files in 'input_files/'.")
        sys.exit(1)
        
    os.makedirs("intermediate_files", exist_ok=True)
    os.makedirs("output_files", exist_ok=True)
    
    print(f"-> Scrubbing affiliations from '{paper_info_path}'...")
    try:
        AffiliationScrubber.scrub(paper_info_path, scrubbed_affiliations_path)
    except Exception as e:
        print(f"Error scrubbing affiliations: {e}")
        sys.exit(1)
        
    print(f"\n-> Generating COI Matrices from '{scrubbed_affiliations_path}' & '{reviewer_exp_path}'...")
    try:
        generate_coi(
            affiliations_path=scrubbed_affiliations_path,
            reviewer_exp_path=reviewer_exp_path,
            input_coi_path=editable_coi_path,
            backup_coi_path=backup_coi_path,
            report_output_path=report_path
        )
    except Exception as e:
        print(f"Error generating COI matrix: {e}")
        sys.exit(1)
        
    print("\n=====================================================")
    print("SUCCESS: COI matrix generation complete.")
    print(f"Action Required: You may review/edit '{editable_coi_path}' before running allocation.")
    print("=====================================================")

if __name__ == "__main__":
    # Ensure working directory is the script directory
    os.chdir(Path(__file__).resolve().parent)
    main()
