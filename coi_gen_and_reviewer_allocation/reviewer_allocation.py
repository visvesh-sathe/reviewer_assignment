"""
Reviewer Allocation Script (Colab/Interactive Workflow)
Uses the inputs and matrices generated by the COI script to optimize reviewer assignments.
"""

import sys
import os
from pathlib import Path

# Setup paths to ensure we can import the src modules
current_dir = Path(__file__).resolve().parent
repo_root = current_dir.parent
if str(repo_root) not in sys.path:
    sys.path.insert(0, str(repo_root))
if str(repo_root / "src") not in sys.path:
    sys.path.insert(0, str(repo_root / "src"))
if str(repo_root / ".agents") not in sys.path:
    sys.path.insert(0, str(repo_root / ".agents"))

from assign_reviewers import assign_reviewers

def main():
    print("=====================================================")
    print("        Step 2: Reviewer Allocation Flow             ")
    print("=====================================================\n")
    
    config_path = "input_files/cfg_config.yaml"
    if not os.path.exists(config_path):
        print(f"Error: Missing configuration file '{config_path}'.")
        sys.exit(1)
        
    os.makedirs("intermediate_files", exist_ok=True)
    os.makedirs("output_files", exist_ok=True)
    
    try:
        assign_reviewers(
            config_path=config_path,
            scrub_output="intermediate_files/paper_id_and_affiliations.csv",
            assignment_output="output_files/paper_assignment.csv",
            matching_output="intermediate_files/reviewer_paper_match_score.csv",
            matrix_output="output_files/reviewer_assignment_matrix.csv",
            champ_matrix_output="output_files/champ_assignment_matrix.csv",
            cochamp_matrix_output="output_files/cochamp_assignment_matrix.csv",
            vector_output="output_files/assignment_vector.csv",
            report_dir="output_files"
        )
        print("\n=====================================================")
        print("SUCCESS: Reviewer allocation complete.")
        print("All assignments, matrices, charts, and reports are available in 'output_files/'.")
        print("=====================================================")
    except Exception as e:
        print(f"\nError during allocation: {e}")
        sys.exit(1)

if __name__ == "__main__":
    # Ensure working directory is the script directory
    os.chdir(Path(__file__).resolve().parent)
    main()
