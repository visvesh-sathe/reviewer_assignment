"""
Reviewer Allocation Script (Colab/Interactive Workflow)
Uses the inputs and matrices generated by the COI script to optimize reviewer assignments.
"""

import sys
import os
from pathlib import Path

# Setup paths to ensure we can import the src modules
current_dir = Path(__file__).resolve().parent
repo_root = current_dir.parent
if str(repo_root) not in sys.path:
    sys.path.insert(0, str(repo_root))
if str(repo_root / "src") not in sys.path:
    sys.path.insert(0, str(repo_root / "src"))
if str(repo_root / ".agents") not in sys.path:
    sys.path.insert(0, str(repo_root / ".agents"))

# Self-healing: Ensure PuLP is compatible (< 4.0) with bundled CBC solver
try:
    import pulp
    pulp_ver = getattr(pulp, "__version__", "0.0.0")
    major_ver = int(pulp_ver.split(".")[0]) if pulp_ver and pulp_ver[0].isdigit() else 3
    if major_ver >= 4 or not hasattr(pulp, "PULP_CBC_CMD"):
        print(f"⚠️ Detected PuLP {pulp_ver} (PuLP 4.x removed bundled CBC solver and legacy APIs).")
        print("🔧 Auto-installing compatible PuLP 3.x release ('pulp>=2.8,<4.0')...")
        import subprocess
        subprocess.check_call([sys.executable, "-m", "pip", "install", "-q", "pulp>=2.8,<4.0"])
        print("✅ PuLP downgraded to compatible version. Re-executing script...\n")
        os.execv(sys.executable, [sys.executable] + sys.argv)
except Exception as e:
    pass

import argparse
from assign_reviewers import assign_reviewers

def main():
    parser = argparse.ArgumentParser(description="Reviewer Allocation Optimization Flow")
    parser.add_argument(
        "--config",
        default="input_files/cfg_config.yaml",
        help="Path to configuration YAML file (default: input_files/cfg_config.yaml)",
    )
    parser.add_argument(
        "--max-extra-reviews",
        type=int,
        default=None,
        help="Optional override for max extra reviews per reviewer above minimum baseline",
    )
    parser.add_argument(
        "--reviews-per-paper",
        type=int,
        default=None,
        help="Optional override for number of reviews required per paper (default: loaded from config YAML)",
    )
    parser.add_argument(
        "--excel-template",
        default="input_files/cfg_assignment_sheet_deliverable_template.xls",
        help="Path to assignment sheet deliverable template (default: input_files/cfg_assignment_sheet_deliverable_template.xls)",
    )
    parser.add_argument(
        "--excel-output",
        default="output_files/final_reviewer_assignment_sheet.xls",
        help="Path to final filled assignment spreadsheet (default: output_files/final_reviewer_assignment_sheet.xls)",
    )
    args = parser.parse_args()

    print("=====================================================")
    print("        Step 2: Reviewer Allocation Flow             ")
    print("=====================================================\n")
    
    config_path = args.config
    if not os.path.exists(config_path):
        print(f"Error: Missing configuration file '{config_path}'.")
        sys.exit(1)
        
    os.makedirs("intermediate_files", exist_ok=True)
    os.makedirs("output_files", exist_ok=True)
    
    try:
        assign_reviewers(
            config_path=config_path,
            scrub_output="intermediate_files/paper_id_and_affiliations.csv",
            assignment_output="output_files/paper_assignment.csv",
            matching_output="intermediate_files/reviewer_paper_match_score.csv",
            matrix_output="output_files/reviewer_assignment_matrix.csv",
            champ_matrix_output="output_files/champ_assignment_matrix.csv",
            cochamp_matrix_output="output_files/cochamp_assignment_matrix.csv",
            vector_output="output_files/assignment_vector.csv",
            report_dir="output_files",
            max_extra_reviews=args.max_extra_reviews,
            reviews_per_paper=args.reviews_per_paper,
            excel_template=args.excel_template,
            excel_output=args.excel_output,
        )
        print("\n=====================================================")
        print("SUCCESS: Reviewer allocation complete.")
        print("All assignments, matrices, charts, and reports are available in 'output_files/'.")
        print("=====================================================")
    except Exception as e:
        print(f"\nError during allocation: {e}")
        sys.exit(1)

if __name__ == "__main__":
    # Ensure working directory is the script directory
    os.chdir(Path(__file__).resolve().parent)
    main()
