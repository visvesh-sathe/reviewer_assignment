"""Standalone script to generate Conflict of Interest (COI) matrix from paper affiliations and reviewer expertise."""

import argparse
import os
import sys
from pathlib import Path
import pandas as pd
import yaml

# Ensure src and project root are in sys.path
src_dir = Path(__file__).resolve().parent
project_root = src_dir.parent
if str(src_dir) not in sys.path:
    sys.path.insert(0, str(src_dir))
if str(project_root) not in sys.path:
    sys.path.insert(1, str(project_root))


def normalize_string(s: str) -> str:
    """Normalizes string for comparison."""
    return str(s).strip().lower()


def check_affiliation_match(rev_aff: str, paper_affs_str: str) -> tuple[bool, list]:
    """Checks if reviewer affiliation matches any paper affiliation.
    Returns (is_coi, list_of_matching_paper_affiliations)"""
    if not rev_aff or not paper_affs_str or pd.isna(rev_aff) or pd.isna(paper_affs_str):
        return False, []

    norm_rev = normalize_string(rev_aff)
    if not norm_rev:
        return False, []

    # Keep original and normalized mapping
    raw_affs = [a.strip() for a in str(paper_affs_str).split(";") if a.strip()]
    
    matches = []
    for raw_aff in raw_affs:
        p_aff = normalize_string(raw_aff)
        if norm_rev == p_aff or (len(norm_rev) > 3 and norm_rev in p_aff) or (len(p_aff) > 3 and p_aff in norm_rev):
            matches.append(raw_aff)
            
    if matches:
        # Remove duplicates preserving order
        unique_matches = list(dict.fromkeys(matches))
        return True, unique_matches
    return False, []


def generate_coi(
    affiliations_path: str,
    reviewer_exp_path: str,
    input_coi_path: str = "input_files/coi.csv",
    backup_coi_path: str = "output_files/autogenerated_coi.csv",
    report_output_path: str = "reports/coi_report.txt",
):
    """Generates COI matrix CSV and detailed text report."""
    df_aff = pd.read_csv(affiliations_path, encoding="utf-8", encoding_errors="replace")
    df_exp = pd.read_csv(reviewer_exp_path, encoding="utf-8", encoding_errors="replace")

    # Extract paper IDs and affiliations
    cols_aff_lower = [str(c).strip().lower() for c in df_aff.columns]
    pid_col = next((c for c, cl in zip(df_aff.columns, cols_aff_lower) if cl in ["paper_id", "paperid", "id"]), df_aff.columns[0])
    aff_col = next((c for c, cl in zip(df_aff.columns, cols_aff_lower) if "affiliation" in cl), df_aff.columns[1])

    # Extract reviewer IDs ("Firstname Lastname") and Affiliation
    cols_exp_lower = [str(c).strip().lower() for c in df_exp.columns]
    fname_col = next((c for c, cl in zip(df_exp.columns, cols_exp_lower) if cl in ["firstname", "first_name", "first name"]), df_exp.columns[0])
    lname_col = next((c for c, cl in zip(df_exp.columns, cols_exp_lower) if cl in ["lastname", "last_name", "last name"]), df_exp.columns[1])
    rev_aff_col = next((c for c, cl in zip(df_exp.columns, cols_exp_lower) if "affiliation" in cl), None)

    df_exp["reviewer_id"] = (
        df_exp[fname_col].astype(str).str.strip() + " " + df_exp[lname_col].astype(str).str.strip()
    ).str.strip()

    reviewer_names = df_exp["reviewer_id"].tolist()
    paper_ids = df_aff[pid_col].astype(int).tolist()

    coi_matrix = []
    conflicts_found = 0
    paper_conflicts = {}

    for _, p_row in df_aff.iterrows():
        p_id = int(p_row[pid_col])
        p_affs = str(p_row[aff_col]) if not pd.isna(p_row[aff_col]) else ""
        row_conflicts = []

        for _, r_row in df_exp.iterrows():
            r_name = r_row["reviewer_id"]
            r_aff = str(r_row[rev_aff_col]) if rev_aff_col and not pd.isna(r_row[rev_aff_col]) else ""

            is_coi, matched_affs = check_affiliation_match(r_aff, p_affs)
            if is_coi:
                row_conflicts.append(1)
                conflicts_found += 1
                if p_id not in paper_conflicts:
                    paper_conflicts[p_id] = []
                paper_conflicts[p_id].append({
                    "reviewer": r_name,
                    "rev_aff": r_aff,
                    "matched_affs": matched_affs
                })
            else:
                row_conflicts.append(0)

        coi_matrix.append(row_conflicts)

    report_lines = []
    report_lines.append("=== Conflict of Interest (COI) Report ===")
    report_lines.append(f"Total Papers Evaluated: {len(paper_ids)}")
    report_lines.append(f"Total Reviewers Evaluated: {len(reviewer_names)}")
    report_lines.append(f"Total Conflicts Identified: {conflicts_found}")
    report_lines.append("\n=== Conflicts by Paper ===")
    
    if not paper_conflicts:
        report_lines.append("\nNo institutional conflicts of interest were identified between any paper and reviewer.")
    else:
        for p_id in sorted(paper_conflicts.keys()):
            report_lines.append(f"\nPaper {p_id}:")
            for conflict in paper_conflicts[p_id]:
                r_name = conflict["reviewer"]
                r_aff = conflict["rev_aff"]
                matched_affs = ", ".join(conflict["matched_affs"])
                report_lines.append(f"  - Reviewer: {r_name} (Affiliation: '{r_aff}')")
                report_lines.append(f"    Reason: Matches paper affiliation(s) -> {matched_affs}")

    report_text = "\n".join(report_lines)

    # Save report
    os.makedirs(os.path.dirname(os.path.abspath(report_output_path)), exist_ok=True)
    with open(report_output_path, "w") as f:
        f.write(report_text)

    # Build COI DataFrame
    df_coi = pd.DataFrame(coi_matrix, index=paper_ids, columns=reviewer_names)
    df_coi.index.name = "paper_id"

    # Save input path
    os.makedirs(os.path.dirname(os.path.abspath(input_coi_path)), exist_ok=True)
    df_coi.to_csv(input_coi_path)
    
    # Save backup path
    os.makedirs(os.path.dirname(os.path.abspath(backup_coi_path)), exist_ok=True)
    df_coi.to_csv(backup_coi_path)

    print(report_text)
    print(f"\nSaved editable COI matrix CSV to '{input_coi_path}'")
    print(f"Saved autogenerated backup COI matrix to '{backup_coi_path}'")
    print(f"Saved detailed COI report to '{report_output_path}'")
    return df_coi


def main():
    parser = argparse.ArgumentParser(
        description="Generate COI Matrix from paper affiliations and reviewer expertise."
    )
    parser.add_argument(
        "--config",
        "-c",
        default="input_files/config.yaml",
        help="Path to YAML configuration file (default: input_files/config.yaml)",
    )
    parser.add_argument(
        "--papers",
        "--affiliations",
        dest="affiliations",
        help="Override path to paper affiliations / paper info CSV (default: resolved from YAML config)",
    )
    parser.add_argument(
        "--reviewer-expertise",
        help="Override path to reviewer expertise CSV (default: resolved from YAML config 'reviewer_expertise')",
    )
    parser.add_argument(
        "--input-coi",
        help="Override path to write editable COI matrix CSV (default: resolved from YAML config 'coi')",
    )
    parser.add_argument(
        "--backup-coi",
        help="Override path to write autogenerated backup COI matrix (default: output_files/autogenerated_coi.csv)",
    )
    parser.add_argument(
        "--report",
        default="reports/coi_report.txt",
        help="Path to write COI report text file (default: reports/coi_report.txt)",
    )
    args = parser.parse_args()

    def resolve_path_fallback(p_str: str) -> Path:
        p = Path(p_str)
        if not p.is_absolute() and not p.exists() and (project_root / p).exists():
            return project_root / p
        return p

    config_path = resolve_path_fallback(args.config)
    cfg = {}
    if os.path.exists(config_path):
        try:
            with open(config_path, "r") as f:
                cfg = yaml.safe_load(f) or {}
        except Exception:
            cfg = {}

    input_dir = resolve_path_fallback(cfg.get("input_files_dir", "input_files"))
    output_dir = resolve_path_fallback(cfg.get("output_files_dir", "output_files"))
    report_dir = resolve_path_fallback(cfg.get("report_files_dir", "reports"))
    files_cfg = cfg.get("files", {})

    # 1. Resolve submitted papers affiliations file (prefer intermediate paper_id_and_affiliations if available, otherwise paper_info.csv)
    if args.affiliations:
        aff_path = resolve_path_fallback(args.affiliations)
    else:
        # Check output intermediate scrubbed affiliations
        intermediate_aff = output_dir / Path(files_cfg.get("paper_id_and_affiliations", "intermediate_data/paper_id_and_affiliations.csv"))
        if intermediate_aff.exists():
            aff_path = intermediate_aff
        else:
            paper_info_name = files_cfg.get("paper_info", files_cfg.get("affiliations", "paper_info.csv"))
            aff_path = input_dir / Path(paper_info_name)

    if not aff_path.exists():
        fallback_candidates = [
            input_dir / "paper_id_and_affiliations.csv",
            input_dir / "paper_info.csv",
            output_dir / "paper_id_and_affiliations.csv",
        ]
        for c in fallback_candidates:
            if c.exists():
                aff_path = c
                break

    # 2. Resolve reviewer expertise (contains reviewer names, affiliations, and expertise scores)
    if args.reviewer_expertise:
        exp_path = resolve_path_fallback(args.reviewer_expertise)
    else:
        exp_filename = files_cfg.get("reviewer_expertise", "reviewer_expertise.csv")
        exp_path = input_dir / Path(exp_filename)

    # 3. Resolve outputs
    if args.input_coi:
        in_coi_path = resolve_path_fallback(args.input_coi)
    else:
        coi_filename = files_cfg.get("coi", "coi.csv")
        in_coi_path = input_dir / Path(coi_filename)
        
    if args.backup_coi:
        bk_coi_path = resolve_path_fallback(args.backup_coi)
    else:
        bk_coi_path = output_dir / "autogenerated_coi.csv"

    report_path = resolve_path_fallback(args.report)
    if not args.report and report_dir:
        report_path = report_dir / "coi_report.txt"

    generate_coi(
        affiliations_path=str(aff_path),
        reviewer_exp_path=str(exp_path),
        input_coi_path=str(in_coi_path),
        backup_coi_path=str(bk_coi_path),
        report_output_path=str(report_path),
    )


if __name__ == "__main__":
    main()
